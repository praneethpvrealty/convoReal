export type UiMessageKey = keyof (typeof UI_MESSAGES)['en'];

/** profiles.active_ui_language is CHECK-constrained to these codes, but
 *  an old app build meeting a future column value must still render. */
export function normalizeUiLanguage(value: unknown): UiLanguage {
  return typeof value === 'string' &&
    (UI_LANGUAGES as readonly string[]).includes(value)
    ? (value as UiLanguage)
    : 'en';
}

export function translate(language: UiLanguage, key: UiMessageKey): string {
  return UI_MESSAGES[language][key] ?? UI_MESSAGES.en[key];
}
